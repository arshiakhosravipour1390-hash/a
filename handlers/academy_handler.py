    async def send_level_up(self, user_id, chat_id, old_level, new_level, reward, send_func, send_private_func):
        user = get_user(user_id)
        username = get_user_name(user)
        level_emoji = get_level_emoji(new_level)
        
        features = []
        if new_level >= 2:
            features.append("🎣 **قلاب ماهیگیری** - میتونی ماهی بگیری!")
        if new_level >= 3:
            features.append("🐈 **پیشی** - میتونی پیشی بخری!")
            features.append("💰 **انتقال پوینت** - میتونی پوینت انتقال بدی!")
        if new_level >= 4:
            features.append("🏦 **بانک میویی** - حساب بانکی باز کن!")
            features.append("🎰 **کازینو میویی** - به کازینو بپیوند!")
        if new_level >= 5:
            features.append("❄️ **یخچال میویی** - ماهی‌ها رو ذخیره کن!")
        if new_level >= 6:
            features.append("💎 **معدن الماس** - ماجراجویی در معدن!")
        
        features_text = "\n".join([f"- {f}" for f in features]) if features else "- ادامه بده به میو کردن! 🚀"
        
        # پیام گروهی (با حذف خودکار)
        group_text = (
            f"🎉 **تبریک میویی!** 🐱\n\n"
            f"🌟 {username} به سطح **{to_persian_numbers(new_level)}** رسید! {level_emoji}\n"
            f"💰 پاداش ارتقا: {to_persian_numbers(format_number(reward))} 🪙\n\n"
            f"📌 **قابلیت‌های جدید:**\n"
            f"{features_text}\n\n"
            f"🌸 به راه خودت ادامه بده! 🚀"
        )
        await send_func(chat_id, group_text, auto_delete=True, delete_after=30)
        
        # پیام خصوصی (حذف نمیشه)
        private_text = (
            f"🎉 **تبریک میویی عزیز!** 🐱\n\n"
            f"🌟 سطح تو به **{to_persian_numbers(new_level)}** رسید! {level_emoji}\n"
            f"💰 {to_persian_numbers(format_number(reward))} 🪙 پاداش گرفتی!\n\n"
            f"📌 **قابلیت‌های جدیدت:**\n"
            f"{features_text}\n\n"
            f"📚 **آکادمی میویی:**\n"
            f"- برای آموزش کامل، `آکادمی میویی` رو بفرست.\n\n"
            f"🌸 به راه خودت ادامه بده! 🚀"
        )
        await send_private_func(user_id, private_text)