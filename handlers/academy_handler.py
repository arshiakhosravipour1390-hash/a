class AcademyHandler:
    def __init__(self):
        self.client = None
        self.user_sessions = {}
    
    def set_client(self, client):
        self.client = client
    
    # ============================================================
    # هندلر اصلی
    # ============================================================
    
    async def handle(self, user_id, chat_id, text, message, send_func):
        user = get_user(user_id)
        if not user:
            await send_func(
                chat_id,
                "❌ ابتدا در یک گروه میو کنید تا ثبت نام شوید!",
                reply_to=message.id,
                auto_delete=True,
                delete_after=10
            )
            return
        
        # اگر کاربر در حالت انتخاب بخش یا مطلب هست
        if user_id in self.user_sessions:
            session = self.user_sessions[user_id]
            if session.get("state") == "selecting_section":
                await self._handle_section_selection(user_id, chat_id, text, message, send_func)
                return
            elif session.get("state") == "viewing_topic":
                await self._handle_topic_selection(user_id, chat_id, text, message, send_func)
                return
        
        # اگر عدد بود و کاربر در آکادمی نبود
        if text.isdigit():
            await send_func(
                chat_id,
                "❌ **لطفاً ابتدا `آکادمی میویی` رو بفرست تا وارد بشی!**\n\n"
                "🌸 بعد از ورود، می‌تونی بخش‌ها رو انتخاب کنی.",
                reply_to=message.id,
                auto_delete=True,
                delete_after=10
            )
            return
        
        await self._show_main_menu(user_id, chat_id, message, send_func)
    
