    async def _handle_topic_selection(self, user_id, chat_id, text, message, send_func):
        if text == "بازگشت":
            await self._show_main_menu(user_id, chat_id, message, send_func)
            return
        
        session = self.user_sessions.get(user_id, {})
        section = session.get("section", "")
        
        if section == "start":
            await self._show_start_topic(user_id, chat_id, text, message, send_func)
        elif section == "features":
            await self._show_feature_topic(user_id, chat_id, text, message, send_func)
        elif section == "competition":
            await self._show_competition_topic(user_id, chat_id, text, message, send_func)
        elif section == "help":
            await self._show_help_topic(user_id, chat_id, text, message, send_func)
        else:
            await send_func(
                chat_id,
                "❌ انتخاب نامعتبر! لطفاً دوباره تلاش کن.",
                reply_to=message.id,
                auto_delete=True,
                delete_after=5
            )
    
